import { test, expect } from '@playwright/test'
import { approveUi, at, confirmUi, eventPath, key, login, newChangeUi, post, reset, screenshot } from './helpers'

test.beforeEach(async ({ baseURL, page }) => {
  page.on('pageerror', error => console.error('Browser error:', error.message))
  await reset(baseURL!)
})
test('AT-01 kabar → konfirmasi → satu opsi → v2 → brief Audio → ack → riwayat', async ({ page }, info) => {
  await login(page)
  await page.goto('/changes/new')
  await expect(page.getByLabel('Kabar perubahan')).toBeVisible()
  await screenshot(page, info, 'input')
  await newChangeUi(page)
  await screenshot(page, info, 'interpretation')
  await confirmUi(page)
  const options = page.getByRole('article', { name: /^Opsi \d+:/ })
  await expect(options).toHaveCount(1)
  await expect(options.first()).toContainText(/Tukar.*Talent B.*Panel/)
  await expect(page.getByText(/Lolos batas yang tercatat. Periksa kondisi lapangan sebelum menyetujui./)).toBeVisible()
  await screenshot(page, info, 'compare')
  await approveUi(page)
  await page.reload()
  await expect(page.getByText('Rundown v2', { exact: true })).toBeVisible()
  await login(page, 'Bayu')
  await expect(page.getByRole('article').first()).toContainText('AKSI DIPERLUKAN')
  await expect(page.getByRole('button', { name: 'Sudah dibaca', exact: true })).toHaveCount(1)
  await screenshot(page, info, 'inbox-unread')
  await page.getByRole('button', { name: 'Sudah dibaca', exact: true }).click()
  await expect(page.getByText(/Sudah dibaca pukul .* untuk perubahan CH-\d+ versi 2/).first()).toBeVisible()
  await page.reload()
  await expect(page.getByText(/Sudah dibaca pukul .* untuk perubahan CH-\d+ versi 2/).first()).toBeVisible()
  await screenshot(page, info, 'inbox-ack')
  await login(page, 'Dimas')
  await expect(page.getByText('Belum ada brief untuk peran ini.', { exact: true })).toBeVisible()
  await screenshot(page, info, 'empty-inbox')
  await login(page)
  await page.goto('/history')
  const decision = page.getByRole('article', { name: /Keputusan CH-\d+ v2/ })
  if (info.project.name === 'mobile') await decision.locator('summary').first().click()
  await expect(page.getByRole('listitem', { name: /Audio/ })).toContainText('Sudah dibaca')
  await expect(page.getByText(/Sudah dibaca pukul/).first()).toBeVisible()
  await screenshot(page, info, 'history')
})

test('AT-05 nama talent dan waktu relatif meminta klarifikasi tanpa mutasi rundown', async ({ page }, info) => {
  await login(page)
  await newChangeUi(page, 'talent telat, 40 menit lagi baru sampai', true)
  await expect(page.getByText('Talent yang mana?', { exact: false }).first()).toBeVisible()
  await expect(page.getByLabel(/Waktu acuan kabar .*wajib diklarifikasi/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Konfirmasi tafsiran', exact: true })).toBeDisabled()
  await expect(page.getByRole('radio')).toHaveCount(2)
  const detail = (await (await page.request.get(new URL(page.url()).pathname.replace('/changes/', '/api/changes/'))).json()).data
  expect(detail.analysis).toBeNull()
  expect(detail.change.confirmed_delta).toBeNull()
  expect(detail.event.active_version).toBe(1)
  await screenshot(page, info, 'clarification')
})

