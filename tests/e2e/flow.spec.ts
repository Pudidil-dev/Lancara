test('AT-10 pembatalan keputusan setelah Panel berlangsung ditolak, riwayat utuh', async ({ page, baseURL }, info) => {
  await login(page)
  await newChangeUi(page)
  await confirmUi(page)
  await approveUi(page)
  let version = 2
  for (const [item_id, status] of [['opening', 'completed'], ['keynote', 'in_progress'], ['keynote', 'completed'], ['panel', 'in_progress']]) {
    const response = await post<{ new_version: number }>(page.request, `${eventPath}/item-status`, { item_id, status, base_version: version, idempotency_key: key() }, baseURL!)
    version = response.new_version
  }
  await post(page.request, `${eventPath}/sim-clock`, { sim_clock_at: at('19:20') }, baseURL!)
  await page.goto('/history')
  const summary = page.getByRole('article', { name: /Keputusan CH-\d+ v2/ }).locator('summary').first()
  if (info.project.name === 'mobile') await summary.click()
  await page.getByRole('button', { name: 'Batalkan keputusan', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText(/kompensasi/)
  await dialog.getByRole('button', { name: 'Lanjut ke konfirmasi', exact: true }).click()
  await expect(page).toHaveURL(/\/changes\/[0-9a-f-]{36}$/)
  await confirmUi(page)
  await expect(page.getByText(/LOCKED_ITEM|terkunci|berlangsung/).first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Setujui opsi terpilih', exact: true })).toHaveCount(0)
  await screenshot(page, info, 'locked-compensation')
  const history = (await (await page.request.get(`${eventPath}/history`)).json()).data
  expect(history.decisions).toHaveLength(1)
  expect(history.versions).toHaveLength(version)
})
