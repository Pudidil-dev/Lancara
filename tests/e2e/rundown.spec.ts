import { test, expect, type Page } from '@playwright/test'
import { approveUi, at, confirmUi, eventPath, key, login, newChangeUi, post, reset, screenshot } from './helpers'
import type { Snapshot } from '@/modules/engine/types'

async function rundown(page: Page) {
  const response = await page.request.get(`${eventPath}/rundown`)
  expect(response.ok()).toBeTruthy()
  return (await response.json()).data as { version: number; snapshot: Snapshot; server_now: string }
}
async function manualChange(page: Page, item: string, type: string, value?: string) {
  await page.goto('/changes/new')
  await expect(page.getByRole('button', { name: 'Isi manual', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Isi manual', exact: true }).click()
  await expect(page).toHaveURL(/\/changes\/[0-9a-f-]{36}$/)
  await page.getByLabel('Item (ID, judul, jadwal)', { exact: true }).selectOption(item)
  await page.getByLabel('Jenis perubahan', { exact: true }).selectOption(type)
  if (value) await page.getByLabel(type === 'active_end_estimate' ? 'Estimasi selesai (WIB)' : 'Mulai paling awal (WIB)', { exact: true }).fill(`2026-10-09T${value}`)
}

