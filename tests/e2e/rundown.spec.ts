test('AT-04 Talent B datang lebih cepat: konfirmasi baru tanpa mengembalikan jadwal otomatis', async ({ page }, info) => {
  await login(page)
  await newChangeUi(page)
  await confirmUi(page)
  await approveUi(page)
  await manualChange(page, 'talent-b', 'earliest_start', '19:15')
  await confirmUi(page)
  let current = await rundown(page)
  expect(current.version).toBe(2)
  expect(current.snapshot.items.find(item => item.id === 'talent-b')!.start_at).toBe(at('20:05'))
  const top = page.getByRole('article', { name: /^Opsi 1:/ })
  await expect(top).toContainText('0 item berubah')
  await screenshot(page, info, 'arrived-earlier-preview')
  await approveUi(page, 'Perbarui batas kedatangan; jadwal tetap sesuai keputusan')
  current = await rundown(page)
  expect(current.version).toBe(3)
  expect(current.snapshot.items.find(item => item.id === 'talent-b')!.start_at).toBe(at('20:05'))
  expect(current.snapshot.constraints.find(constraint => constraint.item_id === 'talent-b' && constraint.type === 'earliest_start')!.at).toBe(at('19:15'))
  const history = (await (await page.request.get(`${eventPath}/history`)).json()).data
  expect(history.decisions).toHaveLength(2)
})
