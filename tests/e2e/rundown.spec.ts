test('AT-02 sesi Sponsor molor: estimasi berubah, item terkunci tetap, Panel minimum terjaga', async ({ page, baseURL }, info) => {
  await login(page)
  let version = 1
  for (const [item_id, status] of [['opening', 'completed'], ['keynote', 'in_progress'], ['keynote', 'completed'], ['talent-b', 'in_progress'], ['talent-b', 'completed'], ['sponsor', 'in_progress']]) {
    const result = await post<{ new_version: number }>(page.request, `${eventPath}/item-status`, { item_id, status, base_version: version, idempotency_key: key() }, baseURL!)
    version = result.new_version
  }
  await post(page.request, `${eventPath}/sim-clock`, { sim_clock_at: at('19:55') }, baseURL!)
  const before = await rundown(page)
  await manualChange(page, 'sponsor', 'active_end_estimate', '20:15')
  await page.getByLabel('Nilai ini merupakan perkiraan', { exact: true }).check()
  await confirmUi(page)
  const top = page.getByRole('article', { name: /^Opsi 1:/ })
  await expect(top).toContainText('Panel')
  await expect(top).toContainText('20.15–20.35')
  await screenshot(page, info, 'active-end-estimate')
  await approveUi(page, 'Sponsor molor; Panel dipangkas sesuai minimum')
  const after = await rundown(page)
  expect(after.version).toBe(version + 1)
  expect(after.snapshot.items.find(item => item.id === 'sponsor')!.estimated_end_at).toBe(at('20:15'))
  const panel = after.snapshot.items.find(item => item.id === 'panel')!
  expect(panel.duration_seconds).toBe(20 * 60)
  expect(panel.duration_seconds).toBeGreaterThanOrEqual(panel.min_duration_seconds)
  for (const item of before.snapshot.items.filter(item => item.status !== 'pending')) expect(after.snapshot.items.find(current => current.id === item.id)!.start_at).toBe(item.start_at)
  expect(after.snapshot.items.find(item => item.id === 'sponsor')!.start_at).toBe(at('19:45'))
})

